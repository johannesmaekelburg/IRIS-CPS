def main() -> None:
    import argparse

    parser = argparse.ArgumentParser(
        description='Python analysis pipeline entry point',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python run_analysis.py
  python run_analysis.py --data data/measurements --output results
  python run_analysis.py --data data/measurements_cps/measurements_cps data/measurements_mfmc
        """,
    )
    default_dirs = [DATA_DIR] if isinstance(DATA_DIR, str) else DATA_DIR
    parser.add_argument(
        '--data',
        nargs='+',
        default=default_dirs,
        metavar='DIR',
        help='One or two data directories containing results_scenario_*.json files',
    )
    parser.add_argument('--output', default=OUTPUT_DIR, help='Output root directory (default: %(default)s)')
    args = parser.parse_args()

    data_dirs  = args.data
    output_dir = str(Path(args.output) / _output_name_for_dirs(data_dirs))

    print('=' * 60)
    print('ANALYSIS PIPELINE')
    for d in data_dirs:
        print(f'  Data:   {d}')
    print(f'  Output: {output_dir}')
    print('=' * 60)

    # ── Merge multiple data dirs if needed ────────────────────────
    _tmp_ctx = None
    if len(data_dirs) > 1:
        print(f'\nMerging {len(data_dirs)} data directories...')
        _tmp_ctx = tempfile.TemporaryDirectory(prefix='cps_analysis_')
        tmp_root = Path(_tmp_ctx.name)
        data_dir = _merge_data_dirs(data_dirs, tmp_root)
        print(f'  Merged into: {data_dir}\n')
    else:
        data_dir = data_dirs[0]

    try:
        # ── MFMC ──────────────────────────────────────────────────────
        if RUN_MFMC:
            print()
            print('=' * 60)
            print('MFMC VARIANCE REDUCTION  (Python)')
            print('=' * 60)
            _run_mfmc(data_dir)

        # ── Sensitivity + heatmaps (via run_full_analysis) ────────────
        if RUN_SENSITIVITY or RUN_HEATMAPS:
            run_complete_analysis(
                data_dir=data_dir,
                output_dir=output_dir,
                analysis_type='sensitivity',
                threshold=THRESHOLD,
                run_sobol=SOBOL_INDICES,
                problem_file=PROBLEM_FILE,
            )

        # ── Metric comparison ablation (independent) ──────────────────
        if RUN_COMPARISON:
            print()
            print('=' * 60)
            print('METRIC COMPARISON  Jaccard / MC / MFMC')
            print('=' * 60)
            _run_comparison(data_dir, output_dir)

        # ── Saltelli-only analyses ─────────────────────────────────────
        exp_type    = detect_experiment_type(data_dir)
        is_saltelli = (exp_type == 'saltelli')

        if RUN_ANTICAUSAL:
            if not is_saltelli:
                print('[Anticausal] SKIP — requires Saltelli / compound-intervention data.')
            else:
                print()
                print('=' * 60)
                print('ANTICAUSAL INFERENCE  P(θ | I(θ))')
                print('=' * 60)
                _run_anticausal(data_dir, output_dir)

        if RUN_LIKELIHOOD_WEIGHTED:
            if not is_saltelli:
                print('[LW] SKIP — requires Saltelli / compound-intervention data.')
            else:
                print()
                print('=' * 60)
                print('LIKELIHOOD-WEIGHTED INCONSISTENCY  I_LW')
                print('=' * 60)
                _run_likelihood_weighted(data_dir, output_dir)

        if RUN_SURROGATE_FIGURES:
            print()
            print('=' * 60)
            print('RQ2 — GNN SURROGATE FIGURES')
            print('=' * 60)
            _run_surrogate_figures(data_dir, output_dir)

    finally:
        if _tmp_ctx is not None:
            _tmp_ctx.cleanup()


if __name__ == '__main__':
    main()
