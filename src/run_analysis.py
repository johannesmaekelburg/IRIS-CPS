def _merge_data_dirs(dirs: list[str], tmp_root: Path) -> str:
    """
    Merge scenario JSON files from multiple directories into a single
    temporary directory, resolving filename conflicts by offsetting
    scenario numbers and tagging each file's scenario_name with its
    source folder.

    Offset rule: dir[0] keeps original numbers; dir[k] (k>0) gets
    offset k*1000 added to the scenario number.

    Returns the path to the merged temp directory.
    """
    merged_dir = tmp_root / 'merged'
    merged_dir.mkdir(parents=True, exist_ok=True)

    for dir_idx, data_dir in enumerate(dirs):
        src = Path(data_dir)
        offset = dir_idx * 1000
        label  = src.name  # e.g. 'measurements_cps'

        json_files = sorted(src.glob('results_scenario_*.json'))
        if not json_files:
            print(f'  [merge] WARNING: no results_scenario_*.json found in {src}')
            continue

        print(f'  [merge] {label}: {len(json_files)} file(s)  (scenario offset +{offset})')

        for src_file in json_files:
            # Extract original scenario number from filename
            parts = [p for p in src_file.stem.split('_') if p.isdigit()]
            orig_num = int(parts[-1]) if parts else 0
            new_num  = orig_num + offset

            dst_name = f'results_scenario_{new_num}.json'
            dst_file = merged_dir / dst_name

            # Load, tag, and write
            with open(src_file, encoding='utf-8') as fh:
                data = json.load(fh)

            data['data_source']   = label
            data['scenario_name'] = f'{label}/scenario_{orig_num}'

            with open(dst_file, 'w', encoding='utf-8') as fh:
                json.dump(data, fh, indent=2)

        # Also copy the saltelli_problem file if present (first dir wins)
        for prob_file in src.glob('saltelli_problem*.json'):
            dst = merged_dir / prob_file.name
            if not dst.exists():
                shutil.copy2(prob_file, dst)

    return str(merged_dir)


def _output_name_for_dirs(dirs: list[str]) -> str:
    """Build an output folder name from multiple data dir names."""
    names = [Path(d).name for d in dirs]
    return '_plus_'.join(names)


