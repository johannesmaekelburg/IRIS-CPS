def _run_mfmc(data_dir: str) -> None:
    """Apply MFMC correction via Python (mirrors MATLAB Step 3)."""
    from mfmc_correction import load_scenario_results, process_scenario, augment_json

    data_path  = Path(data_dir).resolve()
    json_files = sorted(data_path.glob('results_scenario_*.json'))
    if not json_files:
        print(f'[MFMC] No files found in {data_dir}')
        return

    print(f'[MFMC] Processing {len(json_files)} scenario file(s)...')
    for jf in json_files:
        data = load_scenario_results(jf)
        parts = [p for p in jf.stem.split('_') if p.isdigit()]
        sid   = int(parts[-1]) if parts else 0
        print(f'  scenario_{sid}', end='  ', flush=True)
        result = process_scenario(data, sid)
        if result is None:
            print('[SKIP]')
            continue
        augmented = augment_json(data, result)
        with open(jf, 'w', encoding='utf-8') as f:
            json.dump(augmented, f, indent=2)
        methods = list(result['methods'].keys())
        parts   = [f"{m}:rho={result['methods'][m]['rho']:+.3f}" for m in methods]
        print(f"[{', '.join(parts)}]")
    print('[MFMC] Done.\n')


def _run_comparison(data_dir: str, output_dir: str) -> None:
    """Metric ablation: Jaccard vs MC (all available methods) vs MFMC.
    Also generates Figure C (runtime table) and Figure D (MC convergence)."""
    from metric_comparison import run_metric_comparison_analysis
    out_dir = Path(output_dir) / 'metric_comparison'
    out_dir.mkdir(parents=True, exist_ok=True)
    run_metric_comparison_analysis(data_dir, str(out_dir))

    # ── Figure C: Runtime vs Accuracy table ───────────────────────────────────
    from generate_runtime_table import (
        _load_experiments as _rt_load, build_table, print_table, save_csv, plot_table,
    )
    rt_dir = Path(output_dir) / 'runtime_table'
    rt_dir.mkdir(parents=True, exist_ok=True)
    rt_exps = _rt_load(data_dir)
    has_timing = any(
        k.startswith('timing_')
        for k in (rt_exps[0].get('pre_state', {}).get('inconsistency', {}) or {}).keys()
    ) if rt_exps else False
    if not has_timing:
        print('[Figure C] WARNING: No timing_* fields — re-run MATLAB after instrumentation.')
    else:
        rows = build_table(rt_exps)
        print_table(rows)
        save_csv(rows, rt_dir / 'runtime_table.csv')
        plot_table(rows, rt_dir / 'figC_runtime_vs_accuracy.pdf')
        plot_table(rows, rt_dir / 'figC_runtime_vs_accuracy.png')
        print(f'[Figure C] Saved to {rt_dir}')

    # ── Figure D: MC convergence vs sample count ──────────────────────────────
    from generate_convergence_figure import (
        _load_experiments as _cv_load, collect_convergence_data,
        print_summary, plot_convergence, plot_convergence_per_method,
    )
    cv_dir = Path(output_dir) / 'convergence'
    cv_dir.mkdir(parents=True, exist_ok=True)
    cv_exps = _cv_load(data_dir)
    cv_data = collect_convergence_data(cv_exps)
    print_summary(cv_data)
    plot_convergence(cv_data, cv_dir / 'figD_convergence_all.pdf')
    plot_convergence(cv_data, cv_dir / 'figD_convergence_all.png')
    plot_convergence_per_method(cv_data, cv_dir)
    print(f'[Figure D] Saved to {cv_dir}')

    # ── Figure E: Pre / Post intervention inconsistency ───────────────────────
    from generate_prepost_figure import (
        load_experiments as _pp_load, build_records as _pp_build,
        plot_prepost,
    )
    pp_dir = Path(output_dir) / 'paper_figures'
    pp_dir.mkdir(parents=True, exist_ok=True)
    pp_exps = _pp_load([data_dir])
    pp_recs = _pp_build(pp_exps)
    if pp_recs:
        plot_prepost(pp_recs, pp_dir / 'figE_prepost_intervention')
        print(f'[Figure E] Saved to {pp_dir}')
    else:
        print('[Figure E] WARNING: No pre/post pairs found.')

    # ── Figure F: Runtime comparison (MC vs MFMC vs Surrogate, log-scale) ──────
    # Requires surrogate timing fields from surrogate experiment runs.
    # Skipped until surrogate experiments are available.
    print('[Figure F] Skipped — requires surrogate runtime data (run surrogate experiments first).')

    # ── Figure G: Estimator Accuracy Comparison ──────────────────────────────
    from generate_metric_comparison_figure import (
        load_experiments as _mc_load, build_records as _mc_build,
        plot_metric_comparison,
    )
    mc_exps = _mc_load([data_dir])
    mc_data = _mc_build(mc_exps)
    if any(len(v) > 0 for v in mc_data.values()):
        plot_metric_comparison(mc_data, pp_dir / 'figG_metric_comparison')
        print(f'[Figure G] Saved to {pp_dir}')
    else:
        print('[Figure G] WARNING: No records with all three metrics found.')

    # ── Figure H: Causal effects / local sensitivity / robustness margins ─────
    from generate_causal_sensitivity_figure import (
        load_data as _cs_load, plot_causal_sensitivity,
    )
    cs_rows = _cs_load([data_dir])
    if cs_rows:
        plot_causal_sensitivity(cs_rows, pp_dir / 'figH_causal_sensitivity')
        print(f'[Figure H] Saved to {pp_dir}')
    else:
        print('[Figure H] WARNING: No compound experiments found.')

    # Figures I-L (surrogate accuracy, generalization, speedup, ranking) are
    # generated separately once surrogate model output is available.


def _run_anticausal(data_dir: str, output_dir: str) -> None:
    """Anticausal inference: P(θ | I(θ)) — which parameters drive inconsistency.
    Also generates Figure A (aggregate Sobol) and Figure B (causal vs anticausal)."""
    from anticausal_inference import load_saltelli_results, run_anticausal_inference

    print(f'[Anticausal] Loading compound experiments from {data_dir}...')
    try:
        df = load_saltelli_results(data_dir)
    except (FileNotFoundError, ValueError) as exc:
        print(f'[Anticausal] SKIP — {exc}')
        return

    out_dir = Path(output_dir) / 'anticausal_inference'
    out_dir.mkdir(parents=True, exist_ok=True)
    print(f'[Anticausal] Running inference ({len(df)} experiments → {out_dir})')
    run_anticausal_inference(
        df,
        k=ANTICAUSAL_BINS,
        strategy=ANTICAUSAL_STRATEGY,
        fixed_edges=ANTICAUSAL_EDGES if ANTICAUSAL_STRATEGY == 'fixed' else None,
        out_dir=str(out_dir),
    )
    print('[Anticausal] Done.\n')

    # ── Figure A: aggregate Sobol ─────────────────────────────────────────────
    from generate_paper_figures import (
        _load_all_sobol,
        plot_aggregate_sobol,
    )
    fig_dir = Path(output_dir) / 'paper_figures'
    fig_dir.mkdir(parents=True, exist_ok=True)
    try:
        sobol_data = _load_all_sobol(Path(output_dir))
        print('[Figure A] Generating aggregate Sobol...')
        plot_aggregate_sobol(sobol_data, fig_dir / 'figA_aggregate_sobol.pdf')
        plot_aggregate_sobol(sobol_data, fig_dir / 'figA_aggregate_sobol.png')
        print(f'[Figure A] Saved to {fig_dir}')
    except FileNotFoundError as exc:
        print(f'[Figure A] SKIP — {exc}')


def _run_surrogate_figures(data_dir: str, output_dir: str) -> None:
    """RQ2 figures: GNN accuracy, generalization, and runtime comparison."""
    import subprocess, sys
    fig_dir = Path(output_dir) / 'paper_figures'
    fig_dir.mkdir(parents=True, exist_ok=True)

    cmd = [
        sys.executable, '-m', 'src.learned_surrogate.generate_rq2_figures',
        '--results_dir', SURROGATE_RESULTS_DIR,
        '--data_root',   SURROGATE_DATA_ROOT,
        '--measurements', data_dir,
        '--output',      str(fig_dir),
    ]
    print(f'[RQ2] Running: {" ".join(cmd)}')
    result = subprocess.run(cmd, cwd=str(Path(__file__).parent.parent))
    if result.returncode != 0:
        print('[RQ2] WARNING: surrogate figure generation failed.')
    else:
        print(f'[RQ2] Figures saved to {fig_dir}')


def _run_likelihood_weighted(data_dir: str, output_dir: str) -> None:
    """Likelihood-weighted inconsistency I_LW = Σ wᵢ·I(θᵢ) with fitted prior."""
    from likelihood_weighted_inconsistency import (
        load_saltelli_dataset,
        TruncatedNormalTarget,
        estimate,
        plot_lw,
    )

    print(f'[LW] Loading compound experiments from {data_dir}...')
    try:
        df = load_saltelli_dataset(data_dir)
    except (FileNotFoundError, ValueError) as exc:
        print(f'[LW] SKIP — {exc}')
        return

    out_dir = Path(output_dir) / 'likelihood_weighted'
    out_dir.mkdir(parents=True, exist_ok=True)

    target  = TruncatedNormalTarget(df)
    results = estimate(df, target)
    plot_lw(results, out_dir=str(out_dir))
    print(f'[LW] Figures saved to {out_dir}')
    print('[LW] Done.\n')


